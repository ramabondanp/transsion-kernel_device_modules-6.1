static int lcm_get_modes(struct drm_panel *panel,
					struct drm_connector *connector)
{
	struct drm_display_mode *mode[ILI7838E_MODE_NUM];
	int i;
	u8 mode_num = ILI7838E_MODE_NUM;

	pr_info("sub [LCM] %s begin\n", __func__);

	for (i = 0; i < mode_num; i++) {
		mode[i] = drm_mode_duplicate(connector->dev, &switch_mode[i]);
		if (!mode[i]) {
			dev_info(connector->dev->dev, "sub failed to add mode %ux%ux@%u\n",
				switch_mode[i].hdisplay, switch_mode[i].vdisplay,
				drm_mode_vrefresh(&switch_mode[i]));
			return -ENOMEM;
		}

		drm_mode_set_name(mode[i]);
		mode[i]->type = DRM_MODE_TYPE_DRIVER | DRM_MODE_TYPE_PREFERRED;
		drm_mode_probed_add(connector, mode[i]);
	}

	g_lcm_fresh_mode = 120;
	connector->display_info.width_mm = 71;
	connector->display_info.height_mm = 157;
	pr_info("sub [LCM] %s end\n", __func__);

	return i;
}

