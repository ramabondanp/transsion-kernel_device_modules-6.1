static void lcm_panel_init(struct lcm *ctx, struct drm_panel *panel)
{
	pr_info("sub [LCM] %s fps=%d begin\n", __func__, g_lcm_fresh_mode);
	mdelay(12);
	ctx->reset_gpio = devm_gpiod_get(ctx->dev, "reset", GPIOD_OUT_HIGH);
	gpiod_set_value(ctx->reset_gpio, 1);
	mdelay(5);
	gpiod_set_value(ctx->reset_gpio, 0);
	mdelay(5);
	gpiod_set_value(ctx->reset_gpio, 1);
	devm_gpiod_put(ctx->dev, ctx->reset_gpio);
	msleep(20);
	#if IS_ENABLED(CONFIG_TRAN_GET_LCM_CUSTOM_INFO)
	if (g_lcm_custom_info == 0x11) {
		push_table(ctx, lcm_initialization_setting,
			sizeof(lcm_initialization_setting) / sizeof(struct LCM_setting_table));
	} else if (g_lcm_custom_info == 0x22) {
		push_table(ctx, lcm_initialization_setting_pr2,
			sizeof(lcm_initialization_setting_pr2) / sizeof(struct LCM_setting_table));
	} else {
		push_table(ctx, lcm_initialization_setting_pir,
			sizeof(lcm_initialization_setting_pir) / sizeof(struct LCM_setting_table));
	}
	#else
	push_table(ctx, lcm_initialization_setting,
		sizeof(lcm_initialization_setting) / sizeof(struct LCM_setting_table));
	#endif

	if (bl_51_dbv) {
		lcm_dcs_write(ctx, bl_tb_page0, ARRAY_SIZE(bl_tb_page0));
		lcm_dcs_write(ctx, bl_tb0, ARRAY_SIZE(bl_tb0));
		#if IS_ENABLED(CONFIG_TRAN_GET_LCM_CUSTOM_INFO)
		if (g_lcm_custom_info == 0x11) {
			lcm_dcs_write(ctx, bl_tb_page53, ARRAY_SIZE(bl_tb_page53));
			if (bl_51_dbv <= 466) {
				lcm_dcs_write(ctx, bl_tb_pwm, ARRAY_SIZE(bl_tb_pwm));
			} else {
				lcm_dcs_write(ctx, bl_tb_dc, ARRAY_SIZE(bl_tb_dc));
			}
			lcm_dcs_write(ctx, bl_tb_page0, ARRAY_SIZE(bl_tb_page0));
		}
		#endif
		lcm_dcs_write(ctx, bl_tb_page20, ARRAY_SIZE(bl_tb_page20));
		switch (g_lcm_fresh_mode) {
		case MODE_0_FPS:
			mode_switch_to_120(panel, AFTER_DSI_POWERON);
			break;
		case MODE_1_FPS:
			mode_switch_to_90(panel, AFTER_DSI_POWERON);
			break;
		case MODE_2_FPS:
			mode_switch_to_60(panel, AFTER_DSI_POWERON);
			break;
		case MODE_3_FPS:
			mode_switch_to_45(panel, AFTER_DSI_POWERON);
			break;
		case MODE_4_FPS:
			mode_switch_to_30(panel, AFTER_DSI_POWERON);
			break;
		case MODE_5_FPS:
			mode_switch_to_10(panel, AFTER_DSI_POWERON);
			break;
		}
	}

	ctx->error = 0;
	g_dim_enable = 0;
	g_need_dim_enable = 0;
	g_bl_dc_enable = 1;
	g_bl_ac_enable = 0;
	g_dim_dc_enable = 0;
	g_dim_ac_enable = 0;
	pr_info("sub [LCM] %s end\n", __func__);
}

static int lcm_disable(struct drm_panel *panel)
{
	struct lcm *ctx = panel_to_lcm(panel);

	pr_info("sub [LCM]%s, status=%d\n", __func__, ctx->enabled);

	if (!ctx->enabled)
		return 0;

	if (ctx->backlight) {
		ctx->backlight->props.power = FB_BLANK_POWERDOWN;
		backlight_update_status(ctx->backlight);
	}

	ctx->enabled = false;

	return 0;
}

static int lcm_unprepare(struct drm_panel *panel)
{
	struct lcm *ctx = panel_to_lcm(panel);

	if (!ctx->prepared)
		return 0;
	pr_info("sub [LCM] %s begin\n", __func__);
	if (g_aod_enable == 1) {
		pr_info("sub %s aod is enabled\n", __func__);
		push_table(ctx, aod_mode_exit_setting,
			sizeof(aod_mode_exit_setting) / sizeof(struct LCM_setting_table));

		g_aod_enable = 0;
		msleep(34);
	}

	push_table(ctx, lcm_suspend_setting,
		sizeof(lcm_suspend_setting) / sizeof(struct LCM_setting_table));

	ctx->error = 0;
	ctx->prepared = false;
	g_hbm_enable = 0;
	pr_info("sub [LCM] %s end\n", __func__);
	return 0;
}

static int lcm_prepare(struct drm_panel *panel)
{
	struct lcm *ctx = panel_to_lcm(panel);
	int ret;

	pr_info("sub [LCM] %s begin status=%d\n", __func__, ctx->prepared);
	if (ctx->prepared)
		return 0;

	lcm_panel_init(ctx, panel);

	ret = ctx->error;
	if (ret < 0)
		lcm_unprepare(panel);

	ctx->prepared = true;

#ifdef PANEL_SUPPORT_READBACK
	lcm_panel_get_data(ctx);
#endif
	pr_info("sub [LCM] %s end\n", __func__);
	return ret;
}

static int lcm_enable(struct drm_panel *panel)
{
	struct lcm *ctx = panel_to_lcm(panel);

	pr_info("sub [LCM] %s, status=%d\n", __func__, ctx->enabled);

	if (ctx->enabled)
		return 0;

	if (ctx->backlight) {
		ctx->backlight->props.power = FB_BLANK_UNBLANK;
		backlight_update_status(ctx->backlight);
	}

	ctx->enabled = true;

	return 0;
}

