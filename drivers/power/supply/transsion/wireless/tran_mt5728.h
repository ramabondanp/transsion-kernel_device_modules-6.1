struct tx_product_info{
	union {
		u16 data;
		struct {
			u8 tx_imax:4;
			u8 tx_type:2;
			u8 tx_id:2;
			u8 magnetic_type:2;
			u8 tx_vol:3;
			u8 tx_mode:2;
		};
	};
};

